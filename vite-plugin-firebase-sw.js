import fs from 'node:fs'
import path from 'node:path'
import { loadEnv } from 'vite'

/**
 * Writes public/firebase-messaging-sw.js from VITE_FIREBASE_* on configureServer / buildStart.
 * Background notification+data payloads are shown by the browser once — we only
 * call showNotification for data-only messages to avoid duplicates.
 */
export function firebaseMessagingSwPlugin() {
  function writeSw(mode, root) {
    const env = loadEnv(mode, root, '')
    const config = {
      apiKey: String(env.VITE_FIREBASE_API_KEY || '').trim(),
      authDomain: String(env.VITE_FIREBASE_AUTH_DOMAIN || '').trim(),
      projectId: String(env.VITE_FIREBASE_PROJECT_ID || '').trim(),
      storageBucket: String(env.VITE_FIREBASE_STORAGE_BUCKET || '').trim(),
      messagingSenderId: String(env.VITE_FIREBASE_MESSAGING_SENDER_ID || '').trim(),
      appId: String(env.VITE_FIREBASE_APP_ID || '').trim(),
    }
    const configured = Boolean(
      config.apiKey && config.projectId && config.messagingSenderId && config.appId,
    )
    const body = configured
      ? `/* Auto-generated by vite-plugin-firebase-sw — do not edit. */
/* eslint-disable */
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js');
firebase.initializeApp(${JSON.stringify(config)});
var messaging = firebase.messaging();

function resolvePath(data) {
  data = data || {};
  var leadId = String(data.leadId || '').trim();
  if (leadId) return '/leads/' + encodeURIComponent(leadId);
  var href = String(data.href || '').trim();
  if (href.indexOf('http') === 0) {
    try { return new URL(href).pathname + new URL(href).search; } catch (e) { return '/'; }
  }
  if (href.charAt(0) === '/') return href;
  return '/';
}

messaging.onBackgroundMessage(function (payload) {
  // When FCM includes a notification block, the browser already displays it.
  if (payload && payload.notification) {
    return;
  }
  var data = (payload && payload.data) || {};
  var title = String(data.title || 'FILOS CRM');
  var body = String(data.body || '');
  var path = resolvePath(data);
  return self.registration.showNotification(title, {
    body: body,
    data: Object.assign({}, data, { href: path, path: path }),
    tag: String(data.notificationId || path || 'filos-crm'),
    renotify: false,
  });
});

self.addEventListener('notificationclick', function (event) {
  event.notification.close();
  var data = (event.notification && event.notification.data) || {};
  var path = String(data.path || '').trim() || resolvePath(data);
  event.waitUntil((async function () {
    var all = await clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (var i = 0; i < all.length; i += 1) {
      var client = all[i];
      if ('focus' in client) {
        await client.focus();
        client.postMessage({ type: 'melo-notification-click', path: path });
        return;
      }
    }
    if (clients.openWindow) {
      await clients.openWindow(path);
    }
  })());
});
`
      : `/* Firebase web push not configured — placeholder service worker. */
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));
`
    const outPath = path.join(root, 'public', 'firebase-messaging-sw.js')
    fs.mkdirSync(path.dirname(outPath), { recursive: true })
    fs.writeFileSync(outPath, body, 'utf8')
  }

  return {
    name: 'firebase-messaging-sw',
    configResolved(config) {
      writeSw(config.mode, config.root)
    },
    configureServer() {
      // Ensure SW exists as soon as `vite` starts (loads .env.local).
      writeSw(process.env.NODE_ENV === 'production' ? 'production' : 'development', process.cwd())
    },
    buildStart() {
      writeSw(process.env.NODE_ENV === 'production' ? 'production' : 'development', process.cwd())
    },
  }
}
